// **سِجلُّ الشاشات** — الوصلةُ بين نوع العقدة ومُصيِّر شاشتها.
//
// ————— بذرةُ المنصة (`docs/SEED.md §٢`) — منقولٌ من «اِحْسِبْ» بلا حرف —————
//
// عهدُ البذرة: «**الشاشةُ تسجّل نفسَها**» — فلا يعرف الموجِّهُ شاشةً بعينها، ومحطةٌ
// جديدة تدخل الرحلة بلا سطرٍ يُعدَّل فيه. وحين جاءت أوّلُ شاشةِ تمارين حقيقية هناك
// ظهر أنّ السجلَّ **لا يمكن أن يسكن `main.js`**، لسببين لا مخرجَ منهما:
//
//   ١) **دَورٌ في الاستيراد**: `main.js` يستورد وحدةَ التمارين لتُحمَّل، ووحدةُ
//      التمارين تستورد `registerScreen` منه. ووحداتُ ES تُقيَّم بعد اعتماداتها،
//      فيعمل جسمُ وحدة التمارين **قبل** جسم `main.js` — و`screens` ما زالت في منطقة
//      الموت (TDZ) فيسقط التطبيق عند أول تحميل.
//   ٢) **عقدُ المولّد النقيّ**: وحدةُ التمارين تُستورَد في `node` بلا متصفّح ليُجرَد
//      ما تستهلكه (`check_range` · `check_coupling` — `METHOD.md §١١`)، و`main.js`
//      يمسّ الـDOM وقت التحميل — فاستيرادُه منها ممنوعٌ نصّاً.
//
// فصار السجلُّ وحدةً محايدة يستوردها الطرفان: الشاشةُ تسجّل نفسَها، والموجِّهُ يقرأ.
// ولا DOM هنا ولا حالةَ طفل — فتُستورَد في `node` بلا شيء.

const screens = new Map();

/**
 * تسجيل شاشةٍ لنوع عقدة: `render(part)` تُرجِع عنصرَ الشاشة أو `null`.
 * تناديها وحدةُ التمارين مرّةً عند تحميلها — ولا يعرف الموجِّهُ اسمَ شاشةٍ واحدة.
 */
export function registerScreen(type, render) {
  screens.set(type, render);
}

/** أَلِهذا النوع شاشةٌ مسجَّلة؟ (يسأله الموجِّه قبل أن يفتح). */
export const hasScreen = (type) => screens.has(type);

/** مُصيِّرُ شاشة هذا النوع أو `null`. */
export const screenFor = (type) => screens.get(type) || null;

/** أنواعُ الشاشات المسجَّلة — للعدّة والتشخيص، لا لشاشة طفل. */
export const registered = () => [...screens.keys()];

// ————— مسبارُ الإنضاج: «عقدةٌ تنتظر نضجَ مادّتها» (بلاغُ الميدان ٣) —————
//
// **العلّةُ مقيسة**: عقدةُ قصةٍ خطتُها لا تُبنى بحالة الطفل (كلمةٌ من نصّها لم تنضج
// سمعاً) كانت تُعرَض في الخريطة **كالمفتوحة سواءً**، فلمسُها يعود بالطفل إلى الخريطة
// صامتاً — «زرٌّ ظاهرُه حيٌّ ولمستُه ميتة». والحالُ ثالثةٌ لا ثانية: **مقفلةٌ**
// (لم يبلغها) · **مفتوحةٌ** (تُلعَب اليوم) · **تنضج** (بلغها ومادّتُها تنمو بالمراجعة).
//
// **ولا يعرف الموجِّهُ نوعَ عقدةٍ بعينه** كما هو عهدُ السجلّ: مَن يملك النوعَ يعلن
// مسبارَه، والخريطةُ تسأل السجلَّ فترسم الحالَ الثالثة لمن أعلنها. ومَن لم يعلن فلا
// حالَ ثالثةَ له — لا سطرَ يُعدَّل هنا ولا في `main.js`.
//
// **والمسبارُ رخيصٌ عن قصد**: تُرسَم الخريطةُ بعشرات العقد، فلا يبني خطةً ولا جلسةً —
// يردّ **مفاتيحَ السمع التي تنتظرها العقدة** (أو `null` إن لم تنتظر شيئاً).

const ripening = new Map();

/**
 * تسجيل مسبار إنضاجٍ لنوع عقدة: `probe(part) => string[]|null` — مفاتيحُ السمع
 * التي تنتظرها العقدة لتكتمل مادّتُها، أو `null` إن كانت مادّتُها تامّةً اليوم.
 */
export function registerRipening(type, probe) {
  ripening.set(type, probe);
}

/** مسبارُ إنضاج هذا النوع أو `null` (لا حالَ ثالثةَ لمن لم يعلن). */
export const ripeningFor = (type) => ripening.get(type) || null;
