export const GATES = [];

/**
 * **أقسامُ الرحلة بالترتيب** — الوصلةُ الوحيدة بين المنهج والواجهة.
 *
 * يُرجِع مصفوفةَ أقسامٍ، كلُّ قسمٍ يصف نفسَه للخريطة ويحمل عقدَه:
 *
 * ```
 * {
 *   kind,            // نوعُ القسم (مرحلةٌ · عهدٌ · بوابة) — للتنسيق لا للمنطق
 *   id,              // معرّفٌ فريد (تصفيرُ المحطة في لوحة الوالد يستعمله)
 *   title, sub,      // ما يُقرأ على الخريطة (نصٌّ للوالد — لا وسيلةَ تشغيلٍ للطفل)
 *   face, mark,      // وجهُ القسم ومعلمُه البصريّ (اختياريان)
 *   accent,          // متغيّرُ لونِ القسم من `app.css` (اختياريّ)
 *   nodes: [ { id, type, part, title, face } ]   // عقدُه بالترتيب
 * }
 * ```
 *
 * **والعقدةُ معرّفُها `<النوع>:<الجزء>`** — والنوعُ هو ما يوجّه به `main.js` إلى
 * شاشتها، وهو نفسُه ما يُجرَد في `test_measure.mjs` (قياساً أو إعفاءً مكتوباً).
 */
export function sections() {
  return [];
}

/** البوابةُ التي تقف قبل هذا الموضع، أو `null` — بيانٌ مُعلَن لا شرطٌ مضمر. */
export function gateBefore(where) {
  return GATES.find((gate) => gate.after === where) || null;
}

/** بوابةٌ بمعرّفها (تستعملها شاشةُ البوابة في `gate.js`). */
export function gateById(id) {
  return GATES.find((gate) => gate.id === id) || null;
}

/**
 * **مدى البوابة**: مفاتيحُ المهارات التي تسأل عنها هذه البوابة من أضعف ما في يد
 * الطفل (`METHOD.md §٤`: «من **أضعف** مهارات س١–س٤»). ولولا المدى لَتصدّر جلسةَ
 * بوابةِ الفكّ ضعفٌ في السمع، فمرّ الطفل إلى القراءة وفكُّه متزعزع — وهي عينُ
 * العلّة التي وُجدت البوابةُ لها.
 */
export function gateSkills(id) {
  return gateById(id)?.scope || [];
}

