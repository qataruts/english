export const UNIT_SECTIONS = [];

/**
 * **وصفُ وحدةِ قياسٍ** (الحقلُ الأول من مفتاح ليتنر — `word` · `verb` · `pair` ·
 * `phon` · `oral` · `rhyme` · `gpc` · `vowel` · `tricky` · `text`) — **الجلسة ١**.
 * الشكل المتوقَّع: `{ section, title, does: 'يعرف {ما} سمعاً', needs: '…{ما}…' }`.
 */
export function unitOf(unit) {
  return UNIT_UNITS.find((u) => u.id === unit) || null;
}

/** جدولُ الوحدات — **الجلسة ١** تملؤه، ويقرؤه `unitOf` وحده. */
export const UNIT_UNITS = [];

/**
 * **المدى بعبارة الوالد**: يترجم الحقلَ الثاني من المفتاح (`cat` · `p-b` · `h05` …)
 * إلى ما يقرؤه بالغٌ عربيّ — **الجلسة ١**. والمجهولُ يُردّ كما هو لا يُخفى.
 */
export function rangeText(range) {
  return String(range ?? '');
}

/**
 * **ترتيبُ الوحدات كما لقيها الطفل** لا كما تُرتَّب حروفُها — تقرؤه اللوحة فتعرض
 * الوحداتِ بترتيب الرحلة داخلَ كل قسم. **الجلسة ١** (تُشتقّ من `stations()`).
 */
export function journeyUnits() {
  return [...new Set(stations().flatMap((s) => (s.skills || []).map((k) => k.split('|')[0])))];
}
