const listeners = new Set();

/** حالةُ المخزن: `{on}` وما أطفأه وليُّ الأمر من المقابض (`key: false`) لا غير. */
let state = read();

function read() {
  try {
    const raw = globalThis.localStorage?.getItem(STORE_KEY);
    const data = raw ? JSON.parse(raw) : null;
    return data && typeof data === 'object' ? data : {};
  } catch {
    return {};
  }
}

function save() {
  try {
    globalThis.localStorage?.setItem(STORE_KEY, JSON.stringify(state));
  } catch {
    console.warn('[support] تعذّر الحفظ في localStorage');
  }
  for (const fn of listeners) fn();
}

/** يُنادى عند كل تبديل (يستعمله `main.js` ليصبغ صنفَي الهدوء والمؤشّر على الجذر). */
export function onChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

