// **وحدةٌ مستقلة عمداً** — والعلّةُ عندنا **أقوى منها عند اقرأ**: هناك يمنع حارسُ
// الخصوصية أيَّ `https://` في وحدةٍ يمرّ بها صوتُ الطفل، وهنا **لا صوتَ طفلٍ في
// التطبيق أصلاً** (`SEED.md §٥·٣`: «بابٌ لا يوجد» — لا `recorder.js` ولا تسجيل).
// فالفصلُ يحفظ ذلك الحال: `parent.js` — وهي أقربُ ملفٍّ إلى بيانات الطفل — تبقى
// **صفرَ عناوينَ خارجية**، فيبقى السطحُ المُدقَّق نظيفاً بالبناء لا بالانتباه.
//
// ولا يعرف هذا الملفُّ الشبكةَ: رابطا `<a>` يُفتحان بنقرة الراشد ولا يُجلَبان،
// وسياقُهما اسمُ التطبيق وقشرتُه فقط — **لا شيءَ من بيانات الطفل أبداً**.

import { h, BRAND } from './ui.js';

/** **«بلِّغنا»** (أمرُ المالك: «اجعلها بسيطة»): بابُ الجمهور لكل خطأٍ أو مقترح —
 *  من لوحة وليّ الأمر وحدَها (فعلُ راشدٍ متعمَّد خلف بوابةٍ حسابية، ولا زرَّ في
 *  شاشة طفل)، رابطا واتساب وبريدٍ **مملوءان بسطر سياقٍ** يجعل البلاغ قابلاً للعمل
 *  (التطبيقُ ونسخةُ قشرته) — **ولا يُرفَق من بيانات الطفل شيءٌ أبداً**، والمرسِل
 *  يرى نصَّه كاملاً في تطبيقه قبل الإرسال. `<a>` خارجيان يُفتحان إن نُقرا ولا
 *  يُجلَبان — صفرُ شبكةٍ من التطبيق نفسِه. */
export function feedbackSection() {
  /** سطرُ السياق: اسمُ التطبيق ونسخةُ القشرة العاملة — **ولا حرفَ سواهما**.
   *  والنسخةُ تُقرأ من وسمٍ في الصفحة تكتبه لوحةُ الوالد حين تجيب القشرة (لا
   *  سؤالٌ ثانٍ من هنا)، وبلا جوابٍ يمضي البلاغُ باسم التطبيق وحدَه. */
  const context = () => {
    const v = document.getElementById('app-version')?.dataset?.v || '';
    return `بلاغ من تطبيق ${BRAND}${v ? ` (قشرة ${v})` : ''}:\n`;
  };
  const wa = h('a', { class: 'btn', target: '_blank', rel: 'noopener' }, 'عبر واتساب');
  const mail = h('a', { class: 'btn' }, 'عبر البريد');
  const arm = () => {
    const text = context() + 'اكتب ملاحظتك هنا — وأرفق لقطة شاشة إن أمكن.';
    wa.href = `https://wa.me/97433882806?text=${encodeURIComponent(text)}`;
    mail.href = `mailto:info@mishkat.qa?subject=${encodeURIComponent(`بلاغ من تطبيق ${BRAND}`)}`
      + `&body=${encodeURIComponent(text)}`;
  };
  arm();
  navigator.serviceWorker?.addEventListener?.('message', (e) => {
    if (e.data?.type === 'version') arm();     // النسخة وصلت — يدخل رقمُها السياق
  });
  return h('div', {},
    h('p', { class: 'hint' },
      'وجدتَ خطأً؟ عندك اقتراح؟ رسالتُك تصلنا مباشرة — وتُفتح في تطبيقك فترى نصَّها'
      + ' قبل إرسالها، ولا يُرفَق معها شيءٌ من بيانات طفلك.'),
    h('div', { class: 'row', css: { 'justify-content': 'flex-start' } }, wa, mail),
  );
}
