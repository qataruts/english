// ————— لماذا وحدةٌ مستقلّة (نظيرُ `render.js` عند «اِحْسِبْ») —————
//
// شاشتان تريان الشيءَ نفسَه: «افهم والمس» (س١) و«اسمع ونفّذ» (س٢) — كلتاهما تعرض
// صورةً تُلمَس. فلو رسمت كلٌّ لنفسها لَافترق حجمُ الصورة وحدُّها ولونُ إطارها بين
// شاشتين يلقاهما الطفلُ في يومٍ واحد، **ولافترق معهما ما يجرده الحارس**.
//
// وثلاثةُ عهودٍ تحكم هذا الملفّ:
//
// ١) **صدقُ الصورة** (`METHOD.md §٣`): الرسمُ يرسم الكلمةَ نفسَها لا معناها القريب.
