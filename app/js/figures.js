//    اسمٍ فهو في `data-word` — سِمةٌ لا تُرسَم، يقرؤها الفاحصُ ولا تراها عين.
// ٣) **الرسمُ لا يعرف تمريناً**: يأخذ وصفاً ويردّ عنصراً. لا صوتَ فيه ولا قياس ولا
