// ٢ب) أشكالُ الأذن — **جوابٌ عن صوتٍ لا صورةَ له** (س٣ وس٤)
// ————————————————————————————————————————————————————————————————————————
//
// **العلّة، وهي قاعدةُ اللاقراءة بلغتين**: التمييزُ الصوتيّ الخالص (‏/f/ و/v/) سؤالٌ
// عن صوتين لا معنى مصوَّرَ لهما، وجوابُه «سواء» أو «مختلفان» — ولا يُكتب ذلك نصّاً
// يُقرأ. فشكلان يُريان الجوابَ بلا حرف: **دائرتان متطابقتان** سواء، **ودائرةٌ ومثلّث**
// مختلفان. والفارقُ بينهما يُرى من بعيد (قاعدةُ الأوضاع نفسُها).
//
// **وزرُّ الصوت في التقطيع أعمى قصداً**: أزرارُ س٤-٣ تُرتَّب بالسمع لا بالنظر، فلو
// حمل كلٌّ علامةً تميّزه لَصار الترتيبُ نظراً — فكلُّها أذنٌ واحدة، ويعرفها الطفلُ
// **بإسماعها** (الشاشةُ تُسمِع كلَّ زرٍّ في موضعه قبل السؤال، وتُعيد ذلك متى طُلب).

const TOKENS = {
  circle: '<circle cx="0" cy="0" r="11"/>',
  triangle: '<path d="M0 -12.5 12 9 -12 9Z"/>',
};

function tokensEl(kinds = []) {
  const el = h('span', { class: 'fig-tokens', 'aria-hidden': 'true' });
  const at = [-16, 16];
  el.innerHTML = `<svg viewBox="0 0 64 64" fill="none" stroke="currentColor"
    stroke-width="3.4" stroke-linejoin="round">`
    + kinds.map((kind, i) =>
      `<g transform="translate(${32 + at[i]} 32)">${TOKENS[kind] || ''}</g>`).join('')
    + '</svg>';
  return el;
}

/** زرُّ صوتٍ يُرتَّب: أذنٌ واحدة لا تميّز نفسَها — يعرفها الطفلُ بما تُسمِعه. */
function soundEl() {
  const el = h('span', { class: 'fig-sound', 'aria-hidden': 'true' });
  el.innerHTML = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor"
    stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
    <path d="M4 9.5h3.2L12 5.5v13L7.2 14.5H4z"/>
    <path d="M15.6 9.2a4 4 0 0 1 0 5.6"/><path d="M18.3 6.4a8 8 0 0 1 0 11.2"/></svg>`;
  return el;
}

// ————————————————————————————————————————————————————————————————————————
// ٢ج) الرسمُ الإنكليزيّ — **مادّةُ فكٍّ مقصودة** (مسارُ الحرف، الجلسة ٤)
// ————————————————————————————————————————————————————————————————————————
//
// **وهذا ليس نقضاً للعهد الثاني في رأس الملفّ بل حدُّه**: «لا فعلَ يلزم الطفلَ وسيلتُه
// الوحيدة قراءة» (`METHOD.md §٩·٢`) — فالنصُّ **وسيلةُ تشغيلٍ** ممنوع، والرسمُ
// **مادّةُ السؤال نفسِه** هو الدرس. وفي مسار السمع كانت الكلمةُ تُسمَع ولا تُكتب لأنّ
// المقيسَ سمعٌ؛ وهنا يُرسَم الرمزُ لأنّ المقيسَ فكُّه. **وأزرارُ التشغيل تبقى بصورها**
// (أذنٌ · خريطةٌ · إعادة)، ويحرس ذلك جردُ الأزرار في عدّة المتصفّح.
//
// وثلاثةُ قيودٍ على كل رسمٍ يخرج من هنا:
//
//   ١) **`.en` معزولاً** (`enEl` في `ui.js` — `METHOD.md §٩·٣`): مادّةٌ لاتينية في
//      واجهةٍ عربية تُعزَل بـ`unicode-bidi: isolate` فلا تجرّ ما حولها، وتُلفَظ بلسانها
//      عند وسيط الشاشة.
//   ٢) **`data-pending` — خطُّ المادّة نائبٌ معلَن** (ق٥ · `METHOD.md §١٢-٩`): رسومُ
//      التأسيس الطفليّة (‏`a` و`g` بطابقٍ واحد) قرارُ مادّةٍ يُعرَض مع الهوية دفعةً
//      واحدة، والجلسةُ ٤ تمضي بخطّ الواجهة **موسوماً نيابتَه في DOM** — يراه الفاحصُ
//      ويُستبدَل قبل أول عرضٍ على طفل، كما فُعل بالعلامة والوجه (`SEED.md §٨-٢`).
//   ٣) **الوسمُ علامةٌ لا نصّ**: نقطةٌ تحت المقطع المفكوك، وقلبٌ تحت موضع الشوكة
//      (طريقةُ heart words — `METHOD.md §٥`). يتعلّمهما الطفلُ في النمذجة، ولا يُكتب
//      له شرحٌ يُقرأ.

const MARKS = {
  dot: '<circle cx="12" cy="12" r="5"/>',
  // قلبٌ بخطٍّ واحد كأيقونات الواجهة — يُرى من بعيد ولا يُخلَط بالنقطة
  heart: '<path d="M12 20S3.5 14.6 3.5 9.2A4.7 4.7 0 0 1 12 6.4a4.7 4.7 0 0 1 8.5 2.8'
    + 'C20.5 14.6 12 20 12 20Z"/>',
};

/** علامةُ المقطع تحت رسمه — أو لا شيء. */
const markEl = (kind) => {
  if (!MARKS[kind]) return null;
  const el = h('span', { class: `glyph-mark glyph-mark--${kind}`, 'aria-hidden': 'true' });
  el.innerHTML = `<svg viewBox="0 0 24 24" fill="${kind === 'dot' ? 'currentColor' : 'none'}"
    stroke="currentColor" stroke-width="2" stroke-linejoin="round">${MARKS[kind]}</svg>`;
  return el;
};

/**
 * رسمُ كلمةٍ أو رمزٍ بمقاطعه: `parts` = `[{ g, mark }]` — والمقاطعُ متجاورةٌ بلا فراغ
 * (كلمةٌ تُقرأ لا حروفٌ متفرّقة)، ووسمُ كلٍّ تحته.
 */
function letterEl(spec) {
  const box = h('span', { class: 'fig-letters' });
  for (const part of spec.parts || []) {
    // **والفراغُ مقطعٌ مُعلَن لا حرفٌ ناقص** (`gap` — شكلُ الصائت الأوسط): يُرى خطّاً
    // في موضع الصائت، فيعرف الطفلُ **أين** يقع ما يُسأل عنه من الكلمة.
    // **والموضعُ المُعلَّم إشارةٌ لا وسم** (`focus` — نطوقُ ح١٦ البديلة): يقول «عن
    // هذا أسألك» ولا يقول شيئاً عن فكِّه، فلا يُخلَط بالنقطة ولا بالقلب.
    box.append(h('span', {
      class: `glyph${part.gap ? ' glyph--gap' : ''}${part.focus ? ' glyph--focus' : ''}`,
    },
      enEl(part.g, 'en glyph-g'),
      markEl(part.mark)));
  }
  // **النيابةُ تُعلَن في DOM ما دامت قائمة** (حارسُ هويةٍ مبكر — نظيرُ العلامة النائبة)
  box.dataset.pending = 'font';
  return box;
}

