// لا تُسعف: رمزُ الشقلبة ليس وثبةً، ولا رمزَ لـ«اجلس» ولا لـ«المس ذراعك». فتُرسَم
// **أوضاعاً بخطٍّ واحد** كأيقونات الواجهة ومعالمها — لغةُ الرسم عندنا واحدة.
//
// **والفارقُ بين وضعين يجب أن يُرى من بعيد** (لا في تفصيلٍ صغير): ذراعان فوق الرأس
// وثبة، وكفّان تلتقيان تصفيق، وساقان مثنيّتان جلوس. ولذلك بقيت `head` و`hair`
// مرفوعتين: وضعُ لمسهما واحدٌ لعينِ طفل (`RAISED` في `curriculum.js`).

