// ٢) الكمّية — صورةُ العدد **كمٌّ يُعَدّ لا رقمٌ يُقرأ** (قاعدةُ «اِحْسِبْ»)
// ————————————————————————————————————————————————————————————————————————
//
// `METHOD.md §٤` (س١-٦): «الأعداد ١–١٠ سمعاً — عدٌّ مجرد». والرقمُ لا يُكتب على شاشة
// الطفل هنا بحال: يسمع «seven» فيلمس **سبعةَ أشياء**. وصفوفُ الخمسة تجعل السبعةَ
// تُرى صفّاً وشيئاً لا كومةً تُعَدّ من أوّلها في كل مرة.

const ROW = 5;

function countEl(n) {
  const box = h('span', { class: 'fig-count', 'aria-hidden': 'true' });
  for (let i = 0; i < n; i++) {
    box.append(h('span', { class: 'fig-dot' + (i % ROW === 0 && i ? ' fig-dot--wrap' : '') }));
  }
  return box;
}

