/**
 * أسماءُ الأوضاع المرسومة — للعدّة والتشخيص.
 *
 * **والعكسُ محروسٌ حيث يقع**: كلمةٌ تُعلن `pictured: 'act'` ولا وضعَ لها **تسقط من
 * جولات محطتها** (`hasPose` أدناه)، فلا يُرسَم لها فراغٌ — ويمسكها بابُ «لكلِّ
 * مفتاحٍ مادّةٌ تُنتجه بمداه» في `test_measure.mjs` باسمها، لأنّ مفتاحَها يبقى في
 * المنهج ولا تمرينَ يسأل عنه.
 */
export const POSE_NAMES = Object.keys(POSES);

/** أهذه الكلمةُ لها وضعٌ مرسوم؟ (يسأله مولّدُ س٢-٣ قبل أن يولّد جولةً). */
export const hasPose = (word) => Object.hasOwn(POSES, word);

function poseEl(word) {
  const el = h('span', { class: 'fig-pose', 'aria-hidden': 'true' });
  el.innerHTML = `<svg viewBox="0 0 64 64" fill="none" stroke="currentColor"
    stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round">${POSES[word] || ''}</svg>`;
  return el;
}

// ————————————————————————————————————————————————————————————————————————
// ٢) الكمّية — صورةُ العدد **كمٌّ يُعَدّ لا رقمٌ يُقرأ** (قاعدةُ «اِحْسِبْ»)
// ————————————————————————————————————————————————————————————————————————
//
// `METHOD.md §٤` (س١-٦): «الأعداد ١–١٠ سمعاً — عدٌّ مجرد». والرقمُ لا يُكتب على شاشة
// الطفل هنا بحال: يسمع «seven» فيلمس **سبعةَ أشياء**. وصفوفُ الخمسة تجعل السبعةَ
// تُرى صفّاً وشيئاً لا كومةً تُعَدّ من أوّلها في كل مرة.

const ROW = 5;

function countEl(n) {
  const box = h('span', { class: 'fig-count', 'aria-hidden': 'true' });
  for (let i = 0; i < n; i++) {
    box.append(h('span', { class: 'fig-dot' + (i % ROW === 0 && i ? ' fig-dot--wrap' : '') }));
  }
  return box;
}

// ————————————————————————————————————————————————————————————————————————
// ٣) المُصيِّرُ الواحد
// ————————————————————————————————————————————————————————————————————————

/**
 * **شكلٌ من وصفه** — ولكلِّ نمطٍ صورتُه:
 *
 *   `face`   رمزُ Twemoji من `curriculum.js` (صورةٌ محلّية، لا خطُّ نظام)
 *   `count`  كمّيةٌ تُعَدّ (لا رقم)
 *   `swatch` بقعةُ لونٍ بقيمتها المعلَنة (حكمُ المدير — `METHOD.md §٤`)
 *   `ball`   كرةٌ ملوّنة بحجمين — مادّةُ الأمر المركّب (`صفةٌ وصفةٌ ومسمّى`)
 *   `pose`   وضعٌ مرسوم لفعلٍ لا رمزَ ساكناً له
 *
 * @param {object} spec `{ kind, word, face, colour, n, size }`
 * @returns {HTMLElement} عنصرٌ يحمل `data-word` — **اسمُ ما يرسمه، سِمةً لا نصّاً**
 */
export function figureEl(spec) {
  const inner = spec.kind === 'count' ? countEl(spec.n)
    : spec.kind === 'swatch' ? h('span', { class: 'fig-swatch', css: { '--swatch': spec.colour } })
      : spec.kind === 'ball'
        ? h('span', {
          class: `fig-ball fig-ball--${spec.size}`,
          css: { '--swatch': spec.colour },
        })
        : spec.kind === 'pose' ? poseEl(spec.word)
          : emojiImg(spec.face);
  const el = h('span', { class: `fig fig--${spec.kind}` }, inner);
  el.dataset.word = spec.word;
  // **وما وُصف بصفتين يُعرَف بهما** (`the big red ball`): اسمُ الشيء وحدَه لا يميّز
  // كرةً من كرة، والحكمُ على المرسوم يحتاج اسمَ المرسوم تامّاً.
  if (spec.name) el.dataset.name = spec.name;
  // **والكمّيةُ تُعلن معدودَها للفاحص** (لا للطفل): بها يقيس حارسُ المتصفّح أنّ ما
  // رُسم هو ما سُئل عنه — وأرقامُها مشرقيةٌ حيث تُقرأ.
  if (spec.kind === 'count') el.dataset.count = arNum(spec.n);
  return el;
}

/**
 * **وصفُ شكلٍ لكلمةٍ من الرصيد** — القاعدةُ في موضعٍ واحد: تُقرأ من إعلان الكلمة
 * نفسِها (`face` · `count` · `swatch`)، فلا تختار شاشةٌ لكلمةٍ صورةً غيرَ صورتها.
 */
export function specOf(word, extra = {}) {
  if (word.count) return { kind: 'count', word: word.w, n: word.count, ...extra };
  // **والصورةُ قبل البقعة**: تسعةُ ألوانٍ لها مربّعٌ في يونيكود رآه الطفلُ في محطتها،
  // وبقعتُها قيمةٌ للأمر المركّب لا صورةٌ ثانية له (`curriculum.js` — الألوان).
  if (word.face) return { kind: 'face', word: word.w, face: word.face, ...extra };
  if (word.swatch) return { kind: 'swatch', word: word.w, colour: word.swatch, ...extra };
  if (word.pictured === 'act') return { kind: 'pose', word: word.w, ...extra };
  return { kind: 'face', word: word.w, face: '', ...extra };
}
